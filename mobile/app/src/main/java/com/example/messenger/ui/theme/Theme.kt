/**
 * How a Cipher screen gets its colors, type, and shape.
 *
 * 1. Tokens live in [Color.kt] as plain [androidx.compose.ui.graphics.Color] values.
 * 2. This file assigns those tokens to Material 3 *roles* (`primary`, `surfaceContainerLow`, …).
 *    Light and dark each get their own assignment. The role name stays stable.
 * 3. [Type.kt] assigns Plus Jakarta Sans to headlines and Inter to body and labels.
 * 4. [Shape.kt] assigns the radius scale to `MaterialTheme.shapes`.
 * 5. [Spacing.kt] is outside Material, so it is provided with a CompositionLocal.
 * 6. [MessengerTheme] calls `MaterialTheme { content }`. Everything inside `content`
 *    reads `MaterialTheme.colorScheme`, `MaterialTheme.typography`, and
 *    `MaterialTheme.shapes`. No screen should reference a hex value.
 *
 * Dynamic color (the Android 12 wallpaper palette) is intentionally absent.
 * Cipher's cobalt and teal are the product. Letting the wallpaper replace them
 * would make the same button blue on one phone and green on another.
 *
 * @param darkTheme follows the system unless a caller forces a mode.
 */
