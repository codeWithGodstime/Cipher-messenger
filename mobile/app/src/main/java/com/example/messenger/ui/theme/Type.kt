import androidx.compose.ui.unit.sp
import com.example.messenger.R

/**
 * Two families, one job each.
 *
 * Plus Jakarta Sans is the headline face: geometric, a little soft, used for
 * titles. Inter is the workhorse: body copy, labels, and anything small.
 * The files in res/font are static weights (not a variable font) so the
 * weight you ask for is the weight that draws, including on API 24.
 *
 * Each [TextStyle] below is a role. A screen writes
 * `style = MaterialTheme.typography.headlineLarge` and never sets
 * fontFamily, fontSize, or letterSpacing at the call site.
 */

private val PlusJakartaSans = FontFamily(
    Font(R.font.plus_jakarta_sans_semibold, FontWeight.SemiBold),
    Font(R.font.plus_jakarta_sans_bold, FontWeight.Bold),
)

private val Inter = FontFamily(
    Font(R.font.inter_regular, FontWeight.Normal),
    Font(R.font.inter_medium, FontWeight.Medium),
    Font(R.font.inter_semibold, FontWeight.SemiBold),
)

